(() => {
  'use strict';
  const workspace = document.querySelector('.workspace');
  const editor = document.querySelector('.editor-panel');
  const direction = document.querySelector('.direction-panel');
  const preview = document.createElement('section');
  preview.className = 'reference-preview';
  preview.setAttribute('aria-label', 'Prévia do vídeo');
  for (const selector of ['.editor-heading', '.preview-space', '.transport']) preview.append(editor.querySelector(selector));
  const operation = document.createElement('section');
  operation.className = 'reference-operation';
  operation.setAttribute('aria-label', 'Comando e etapas de edição');
  const prompt = document.querySelector('.prompt-box');
  const label = document.createElement('span'); label.className = 'command-label'; label.textContent = 'VOCÊ';
  prompt.prepend(label);
  operation.append(prompt, document.querySelector('.suggestions'), document.querySelector('.action-list'), document.getElementById('deepseek-stop'), document.getElementById('status'));
  const timeline = document.querySelector('.timeline');
  operation.append(timeline);
  workspace.prepend(preview, operation);
  editor.remove();
  const materials = document.createElement('details'); materials.className = 'reference-materials';
  const summary = document.createElement('summary'); summary.textContent = 'Material e projetos';
  materials.append(summary); document.querySelector('.media-panel').before(materials); materials.append(document.querySelector('.media-panel'));
  const mark = document.querySelector('.brand');
  mark.querySelector('.brand-symbol').innerHTML = '<span class="ai-orb">IA</span>';
  mark.querySelector(':scope > span:last-child').textContent = 'EDITOR IA';
  mark.setAttribute('aria-label', 'Editor IA, início'); mark.href = '/editor';
  const statusBadge = document.createElement('span'); statusBadge.className = 'operation-badge'; statusBadge.textContent = 'Pronto para editar';
  document.querySelector('.project-title').append(statusBadge);
  const cursor = document.createElement('div'); cursor.className = 'timeline-cursor'; cursor.setAttribute('aria-hidden','true'); cursor.innerHTML = '<span>IA</span>';
  timeline.append(cursor);
  const player = document.getElementById('video');
  function sync(requestedTime) {
    const track = timeline.querySelector('.track');
    if (track) cursor.style.top = `${track.offsetTop - 20}px`;
    const project = state.project;
    const duration = project?.edit_state?.duration || project?.clean_duration || project?.duration;
    let time = Number.isFinite(requestedTime) ? requestedTime : window.editPlayhead?.() ?? player.currentTime;
    if (!Number.isFinite(requestedTime) && state.sample && !state.final) time += Number(project?.settings?.sample_start || 0);
    const fraction = Number.isFinite(duration) && duration > 0 ? Math.min(1, Math.max(0, time / duration)) : 0;
    const videoTrack = document.getElementById('video-track');
    const trackBounds = videoTrack.getBoundingClientRect();
    const bounds = timeline.getBoundingClientRect();
    cursor.style.left = `${trackBounds.left - bounds.left - timeline.clientLeft + trackBounds.width * fraction}px`;
    timeline.style.setProperty('--cursor-position', String(fraction));
    cursor.hidden = !Number.isFinite(duration) || duration <= 0;
  }
  for (const event of ['timeupdate','loadedmetadata','emptied','seeking','seeked']) player.addEventListener(event, sync);
  window.addEventListener('timeline-seek', event => sync(event.detail));
  window.addEventListener('editor-state', () => sync());
  for (const id of ['video-track','audio-track']) document.getElementById(id).addEventListener('click', event => {
    if (event.target.closest('button') || !state.project || state.busy) return;
    const bounds = document.getElementById(id).getBoundingClientRect();
    const duration = state.project.edit_state?.duration || state.project.clean_duration || state.project.duration;
    const time = Math.min(1, Math.max(0, (event.clientX - bounds.left) / bounds.width)) * duration;
    if (state.sample) setView(false);
    window.editSeek(time);
    updateTime();
  });
  sync();
  new ResizeObserver(sync).observe(timeline);
  const statuses = document.getElementById('status');
  const observer = new MutationObserver(() => {
    const message = statuses.querySelector('p')?.textContent || '';
    statusBadge.textContent = message || 'Pronto para editar';
    statusBadge.classList.toggle('failed', statuses.classList.contains('error'));
    statusBadge.title = message;
  });
  observer.observe(statuses, {childList:true, subtree:true, attributes:true, attributeFilter:['class']});
  direction.setAttribute('aria-label','Ajustes detalhados');
})();
